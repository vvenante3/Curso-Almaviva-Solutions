package listas_arrays;

public class User {
    
    private int code;

    private String name;

    public User() {
    }

    public User(int code, String name) {
        this.code = code;
        this.name = name;
    }

    public int getCode() {
        return code;
    }

    public String getName() {
        return name;
    }

    

}
